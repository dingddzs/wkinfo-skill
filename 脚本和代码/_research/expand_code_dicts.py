def expand(name: str, items: list, prefix: str = "") -> dict:
    print(f"\n=== {name} ===")
    result = {}
    for code, label in items:
        if prefix == "causeOfAction":
            fq = f"+causeOfAction:(({code}{label}))"
        elif prefix == "court":
            fq = f"+court:(({code}{label}))"
        elif prefix == "industryCode":
            fq = f"+industryCode:(({code}))"
        elif prefix == "referenceLevelNew":
            fq = f"+referenceLevelNew:(({code}))"
        else:
            fq = None
        if not fq:
            continue
        count = test(fq.split('+')[1])
        eff = 0 < count < BASE
        marker = "✓" if eff else "✗"
        print(f"  {marker} {code:20s} {label:30s} {count:>12,}")
        result[code] = {"label": label, "count": count, "effective": eff}
    return result


